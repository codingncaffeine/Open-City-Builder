enum WinHtmlFlag : std::uint32_t {
    kHtmlFlag1 = 0x1,               // never set by this class
    kHtmlFlag2 = 0x2,               // on by default, not read by any recovered method (meaning unknown)
    kHtmlHScroll = 0x4,             // a horizontal scrollbar is allowed
    kHtmlVScroll = 0x8,             // a vertical scrollbar is allowed
    kHtmlKeyboardScroll = 0x10,     // the scrolling keys are enabled (the wheel sets it too)
    kHtmlFollowLinks = 0x20,        // a clicked link navigates, and the hand cursor is shown
    kHtmlOutline = 0x40,            // draw the outline colour around the draw area
    kHtmlFillBackground = 0x80,     // fill with the fill colour when there is no body background image
};
constexpr std::uint32_t kHtmlDefaultFlags = 0xfa;

enum WinHtmlLoadStatus : std::int32_t { kHtmlLoadIdle = 0, kHtmlLoadLoading = 1, kHtmlLoadLoaded = 2 };

// The window's drawing buffer, as cGZWinHTML paints it (originally the cIGZBuffer at +0x98). The port's cGZWin keeps its
// buffer behind the IWinBuffer seam, so the engine side adapts it; every method mirrors one original buffer call.
class IWinHtmlCanvas : public html::IHtmlSurface {
public:
    // cIGZBuffer::Lock / Unlock (vslots 0x40 / 0x48). The flags are the html surface flags (kSurfaceFill etc.) plus
    // 0x8008 for the outline.
    virtual bool Begin(std::uint32_t flags) override = 0;
    virtual void End(std::uint32_t flags) override = 0;
    // DrawRectangleOutline(buffer, rect, colour, 1) @ 0x1002b3deb.
    virtual void Outline(const cRZRect& rect, std::uint32_t nativeColor) = 0;
    // RZDrawBltTiled(dest, source, sourceBounds, destRect, offsetX, offsetY, null) @ 0x1006a3062.
    virtual void BltTiled(html::IHtmlBitmap* source, const cRZRect& sourceRect, const cRZRect& destRect,
                          int offsetX, int offsetY) = 0;
};

