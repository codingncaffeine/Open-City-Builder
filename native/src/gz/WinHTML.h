// cGZWinHTML — the HTML viewer window (58 functions, 0x100566a34..0x100569cb6; object of 0x7a8 bytes: cGZWin 0x150 +
// 0x658 of its own state). It is the control the game uses for the in-game help, the news and the advisor pages: it owns
// a cHTMLDocument (the recovered parser/element tree), lays the parsed elements out against a cHTMLDrawContext, paints
// them, and scrolls with two optional scrollbars, the mouse wheel, the arrow / page keys and drag-free link following.
//
// Layout of the original (documented because the members are private and the offsets appear in the neighbours):
//   +0x150 cIGZWinHTML view (iid 0x4a11fd4a; iid 1 also answers this view)
//   +0x158 cIGZMessageTarget2 view (iid 0x452294aa)
//   +0x160 cHTMLDrawContext (0xa0): +0x160 graphics, +0x168 window, +0x170 surface, +0x178 screen rect, +0x188 document
//          rect, +0x1a8 background colour, ...
//   +0x200 cHTMLDocument*            +0x208 cRZCriticalSection (recursive)
//   +0x228 link cursor / +0x230 arrow cursor (cIGZCursor*)
//   +0x238 cRZString missing-bitmap path (default "Missing.jpg", set in Init)
//   +0x260 flags (initial 0xfa)      +0x264..0x270 gutters (l 4, t 4, r 0x16, b 4)
//   +0x274 10, +0x278 1, +0x27c 0, +0x280 1 (initialised, never read by this class)
//   +0x288 vertical scrollbar / +0x290 horizontal (cIGZWinScrollbar*)
//   +0x298 vertical image / +0x2a0 horizontal (cIGZBuffer*), +0x2a8 / +0x2b8 their rectangles
//   +0x2c8 outline colour (0; never written by this class)  +0x2d0 cIGZImageDecoder (GZCOM 0xa2ffb5d3, iid 0x2ffbb60)
//   +0x2d8 cRZCallbackTimer (periodic blink redraw, 500 ms)
//   +0x310 seven-entry text size table (all zero = use the document's own table)
//   +0x330 base URL, +0x4a8 current URL, +0x620 URL being loaded (cRZURL, 0x178 each)
//   +0x798 cIGZWWWSystem (here html::IHtmlWebSystem, borrowed)  +0x7a0 load status (0 idle, 1 loading, 2 loaded)
//
// The document rect at +0x188 is the visible part of the page: its top-left is the scroll position, its size the viewport
// (screen rect size) -- SetHTMLPaintArea recomputes the right/bottom edges from the screen rect and the current scroll.
//
// Quirks kept (each asserted in gz_winhtml_test):
//  * End (VK_END) sets the visible right edge to the visible *height* instead of the width (0x100567e07).
//  * SetScrollBarValues, when a horizontal scrollbar exists, pushes the horizontal range / line / page counts and the
//    horizontal position into the *vertical* scrollbar (0x100568225..0x10056824e).
//  * GZOnMouseWheel always sets the keyboard-scroll flag (0x10) and writes back the flag word it read before the key
//    repeats, so a flag cleared by AddScrollBar during the repeat is resurrected.
//  * SetArea with an unchanged size invalidates the parent (and does nothing when there is no parent) instead of the
//    window itself (0x100568b7e..0x100568b8a).
//  * AddScrollBar counts a failed scrollbar creation as an attempt: the window is invalidated and the bars re-measured
//    even when both creations failed (ClearFlag(8) / ClearFlag(4) already dropped the permission).
//  * GZOnKeyDown notifies the target first (message 0xe4a85d8d) and returns as soon as the target claims the key.
//  * DoLinkJump notifies the target (0xe4a85d91, param2 = the cRZString) and only follows the link when the target's
//    answer is true *and* the follow-links flag (0x20) is set.
//  * The original divides by the visible size when it computes the scrollbar page counts; the port guards 0 (a fault
//    in the original, impossible to assert).
//
// Seams (docs/SEAMS.md is generated by scripts/list_seams.py):
//  * IWinHtmlCanvas / IWinHtmlHost replace the drawing buffer (+0x98) and the framework services (font system, image
//    decoder, WWW system, bullet factory). The embedded WWW system (cGZWWWSystem) is out of the macOS scope
//    (scripts/macos_scope.py), so the download protocol is represented by html::IHtmlWebSystem. The engine side
//    (cGZBuffer as IWinHtmlCanvas, cIGZFontSys as html::IHtmlFontSystem, cGZGimexFactory as html::IHtmlImageDecoder,
//    cGZWWWSystem as html::IHtmlWebSystem) is app/NativeWinHtml.cpp in the native game; the defaults here are null.
